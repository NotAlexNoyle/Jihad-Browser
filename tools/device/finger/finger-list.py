# finger-list.py — docs/FINGER-TESTS.md regenerated from the suite and its last report (cavekit-finger-testing.md R6,
# T-565): every script of tools/device/finger/suite/ is one entry under its `section:` with its `item:` text, the
# shells it names, its kit, and the last report's verdict per shell (pass / fail / a person's / by a tool / not run,
# with the date); a person's items are marked as such. The hand-run record the list used to be is kept as
# docs/FINGER-TESTS-2026-10.md.
#
#   tools/device/finger/finger-list.py [--report docs/rounds/finger-<date>/finger-report.json] [--write]
import os, sys, json, glob, re, datetime
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
sys.path.insert(0, HERE)
import importlib.util
spec = importlib.util.spec_from_file_location("finger_run", os.path.join(HERE, "finger-run.py")); fr = importlib.util.module_from_spec(spec); spec.loader.exec_module(fr)
ORDER = ["Scrolling and gestures", "Keyboard and text", "Chrome, menus and dialogs", "Personas and add-ons", "Fonts", "The engine", "Proxies and certificates", "Media and sound", "Sites", "Not built yet", "Not testable at all"]

def main():
    args = sys.argv[1:]; write = "--write" in args
    rep_path = None
    if "--report" in args: rep_path = args[args.index("--report") + 1]
    else:
        reps = sorted(glob.glob(os.path.join(ROOT, "docs", "rounds", "finger-*", "finger-report.json")))
        rep_path = reps[-1] if reps else None
    report = json.load(open(rep_path)) if rep_path else {"tests": [], "date": ""}
    date = report.get("date", "")[:10]
    verdicts = {}
    for r in report["tests"]: verdicts.setdefault(r["id"], {})[r["shell"]] = r
    tests = [fr.parse(p) for p in sorted(glob.glob(os.path.join(HERE, "suite", "*.test")))]
    by_section = {}
    for t in tests: by_section.setdefault(t["section"] or "Other", []).append(t)
    out = ["# The finger round — every test as a script of the suite (`tools/device/finger/suite/`)", "",
           "**Generated by `tools/device/finger/finger-list.py` from the suite and its last report" + (f" (`{os.path.relpath(rep_path, ROOT)}`, {date})" if rep_path else "") + ".**",
           "Edit a script's `item:` line, not this file. The round is the agent's, driven by the emulated finger on the real",
           "input path (`tools/device/finger/`, `context/kits/cavekit-finger-emulation.md`) and judged by the check library's",
           "oracles (`cavekit-finger-testing.md`); only what no emulation reaches — the accelerometer's rotation, the volume",
           "keys, hearing audio, a physical keyboard — stays a person's, and says so. The hand-run record this list was until",
           "2026-11-05 is `docs/FINGER-TESTS-2026-10.md`.", "",
           "The owner, 2026-10-12: \"defer all finger tests in the entire project for one large round at the end\". The suite",
           "runs them all from one command (`finger-run.py`); the owner's own round compares (T-566).", ""]
    for sec in ORDER + [s for s in by_section if s not in ORDER]:
        if sec not in by_section: continue
        out.append(f"## {sec}"); out.append("")
        for t in by_section[sec]:
            v = verdicts.get(t["id"], {})
            if t["person"]: mark = "[P]"; tail = "**a person's:** " + t["person"]
            elif t["tool"]: mark = "[T]"; tail = "**by a tool:** " + t["tool"]
            elif t["skip"]: mark = "[ ]"; tail = "**not run:** " + t["skip"]
            else:
                parts = []
                for sh in t["shells"]:
                    r = v.get(sh)
                    parts.append(f"{sh} {r['verdict']}" if r else f"{sh} (not in the last report)")
                allpass = v and all(v.get(sh, {}).get("verdict") == "pass" for sh in t["shells"])
                anyfail = any(v.get(sh, {}).get("verdict") == "fail" for sh in t["shells"])
                mark = "[x]" if allpass else ("[!]" if anyfail else "[ ]")
                tail = f"`{t['id']}` on " + ", ".join(parts) + (f" ({date})" if v else "")
                if t["needs"]: tail += f"; needs {', '.join(t['needs'])}"
            kit = f" ({t['kit']})" if t["kit"] else ""
            out.append(f"- {mark} {t['item'] or t['id']}{kit} — {tail}")
        out.append("")
    text = "\n".join(out)
    if write:
        open(os.path.join(ROOT, "docs", "FINGER-TESTS.md"), "w").write(text); print(f"written: docs/FINGER-TESTS.md ({len(tests)} scripts, the report of {date})")
    else: print(text)

if __name__ == "__main__": main()
