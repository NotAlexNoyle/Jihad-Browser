# flash-corpus.py -- the corpus of real Flash titles (cavekit-flash.md R1): a manifest in the repository, the files in a
# cache outside it (they are other people's work and the repository is public), every fact about a file read from the
# file by this tool and not typed.
#
#   flash-corpus.py read FILE...             what a movie or a video is, from its own bytes
#   flash-corpus.py add SOURCE --id ID --class game|app|video|asset --kind KIND --input TEXT --note TEXT [--for ID] [--player ID]
#                                            fetch one title and put it in the manifest. SOURCE is a URL, or ia:ITEM for
#                                            the largest .swf of an archive.org item; ia:ITEM/FILE names the file
#   flash-corpus.py fetch [ID...]            what is missing fetched into the cache, every hash verified; a dead source
#                                            or a changed hash reported by title (exit 1)
#   flash-corpus.py check                    the spread R1 asks for, read from the files; the tracked-movies check (exit 1)
#   flash-corpus.py tracked                  only the check that no third-party movie is tracked
#   flash-corpus.py list                     the manifest as a table
#   flash-corpus.py reread | remove ID...    the facts read again from the cache; a title out of the manifest and the cache
#   flash-corpus.py path ID                  a title's path in the cache
#
# The cache is ~/.cache/jihad-flash (JIHAD_FLASH_CACHE), the manifest flash-corpus.json beside this tool (JIHAD_FLASH_MANIFEST). Rounds serve it over the local network, so an internet failure is
# never a Flash verdict. Run with python3 -I.
import argparse, hashlib, json, lzma, os, struct, subprocess, sys, urllib.parse, urllib.request, zlib

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
MANIFEST = os.environ.get("JIHAD_FLASH_MANIFEST", os.path.join(HERE, "flash-corpus.json"))
CACHE = os.environ.get("JIHAD_FLASH_CACHE", os.path.expanduser("~/.cache/jihad-flash"))
UA = "Mozilla/5.0 (X11; Linux x86_64; rv:128.0) Gecko/20100101 Firefox/128.0"
MOVIE_EXT = (".swf", ".flv", ".f4v")
# generated by this project and parsed back by render/goanna/test/dump-swf.py before a result from them is believed
GENERATED = "render/goanna/test/jihad-"
GAME_KINDS = ("hold", "click", "aim", "arrows", "keys", "heavy")
VIDEO_CODECS = {2: "spark", 3: "screen", 4: "vp6", 5: "vp6a", 6: "screen2", 7: "h264"}


# --- reading a file ---------------------------------------------------------------------------------------------------
class Bits:
    def __init__(self, data, pos=0): self.d, self.p, self.b = data, pos, 0
    def u(self, n):
        v = 0
        for _ in range(n):
            byte = self.d[self.p]
            v = (v << 1) | ((byte >> (7 - self.b)) & 1)
            self.b += 1
            if self.b == 8: self.b = 0; self.p += 1
        return v
    def s(self, n):
        v = self.u(n)
        return v - (1 << n) if n and v >> (n - 1) else v
    def align(self):
        if self.b: self.b = 0; self.p += 1


def read_swf(data):
    sig = data[:3]
    if sig not in (b"FWS", b"CWS", b"ZWS"): raise ValueError("not a SWF")
    version = data[3]; declared = struct.unpack("<I", data[4:8])[0]
    if sig == b"FWS": body = data[8:]
    elif sig == b"CWS": body = zlib.decompressobj().decompress(data[8:])
    else:
        props = data[12:17]; dict_size = struct.unpack("<I", props[1:])[0]; d = props[0]
        lc = d % 9; d //= 9; lp = d % 5; pb = d // 5
        body = lzma.LZMADecompressor(format=lzma.FORMAT_RAW, filters=[{"id": lzma.FILTER_LZMA1, "dict_size": dict_size, "lc": lc, "lp": lp, "pb": pb}]).decompress(data[17:])
    b = Bits(body); nb = b.u(5)
    xmin, xmax, ymin, ymax = b.s(nb), b.s(nb), b.s(nb), b.s(nb); b.align()
    p = b.p; fps = struct.unpack("<H", body[p:p + 2])[0] / 256.0; frames = struct.unpack("<H", body[p + 2:p + 4])[0]; p += 4
    as3 = None; abc = 0; actions = 0; video = set(); sound = 0; stream_sound = 0; ntags = 0; net = False; stage3d = None; inputs = 0
    def edit_is_input(q):                    # DefineEditText: its id, a rect, then the flags; ReadOnly clear is a field that takes text
        rb = Bits(body, q + 2); nn = rb.u(5); rb.u(nn * 4); rb.align()
        return not (body[rb.p] & 0x08)
    def sprite_inputs(q, end):               # the tags of a DefineSprite: an edit text inside one counts
        n_in = 0; q += 4
        while q + 2 <= end:
            hh = struct.unpack("<H", body[q:q + 2])[0]; q += 2
            cc = hh >> 6; ll = hh & 0x3f
            if ll == 0x3f: ll = struct.unpack("<I", body[q:q + 4])[0]; q += 4
            if cc == 0: break
            if cc == 37 and edit_is_input(q): n_in += 1
            q += ll
        return n_in
    while p + 2 <= len(body):
        h = struct.unpack("<H", body[p:p + 2])[0]; p += 2
        code = h >> 6; n = h & 0x3f
        if n == 0x3f:
            if p + 4 > len(body): break
            n = struct.unpack("<I", body[p:p + 4])[0]; p += 4
        if code == 0: break
        ntags += 1
        if code == 69 and n >= 4:              # FileAttributes
            fl = body[p]; as3 = bool(fl & 0x08); net = bool(fl & 0x01); stage3d = bool(fl & 0x40)
        elif code in (72, 82): abc += 1         # DoABC
        elif code in (12, 59): actions += 1     # DoAction, DoInitAction
        elif code == 60 and n >= 10: video.add(VIDEO_CODECS.get(body[p + 9], "codec%d" % body[p + 9]))   # DefineVideoStream
        elif code == 14: sound += 1             # DefineSound
        elif code == 37 and edit_is_input(p): inputs += 1
        elif code == 39: inputs += sprite_inputs(p, p + n)
        elif code in (18, 45): stream_sound += 1
        p += n
    avm = 2 if (abc or as3) else 1
    return {"format": "swf", "compression": sig.decode(), "swf_version": version, "declared_size": declared, "width": round((xmax - xmin) / 20),
            "height": round((ymax - ymin) / 20), "fps": round(fps, 2), "frames": frames, "avm": avm, "tags": ntags, "abc": abc, "actions": actions,
            "embedded_video": sorted(video), "sounds": sound + stream_sound, "gpu_flag": bool(stage3d), "input_fields": inputs}


def read_flv(data):
    if data[:3] != b"FLV": raise ValueError("not an FLV")
    p = struct.unpack(">I", data[5:9])[0] + 4; codec = None; audio = None; w = h = None; sw = sh = None; last = 0
    n = 0
    while p + 11 <= len(data) and n < 400:
        t = data[p]; size = (data[p + 1] << 16) | (data[p + 2] << 8) | data[p + 3]
        ts = ((data[p + 7] << 24) | (data[p + 4] << 16) | (data[p + 5] << 8) | data[p + 6])
        if t == 9 and codec is None and size:
            codec = VIDEO_CODECS.get(data[p + 11] & 0x0f, "codec%d" % (data[p + 11] & 0x0f))
            if codec == "spark":                # the picture header: 17 bits start, 5 version, 8 reference, 3 size
                b = Bits(data, p + 12); b.u(30); sz = b.u(3)
                if sz in (0, 1): n2 = 8 if sz == 0 else 16; sw, sh = b.u(n2), b.u(n2)
                else: sw, sh = {2: (352, 288), 3: (176, 144), 4: (128, 96), 5: (320, 240), 6: (160, 120)}.get(sz, (None, None))
        if t == 8 and audio is None and size: audio = {0: "pcm", 1: "adpcm", 2: "mp3", 5: "nelly8", 6: "nelly", 10: "aac", 11: "speex"}.get(data[p + 11] >> 4, "audio%d" % (data[p + 11] >> 4))
        if t == 18 and w is None:              # onMetaData: width and height as doubles after their names
            meta = data[p + 11:p + 11 + size]
            for key, _ in ((b"width", 0), (b"height", 0)):
                i = meta.find(struct.pack(">H", len(key)) + key)
                if i >= 0 and meta[i + 2 + len(key)] == 0:
                    v = struct.unpack(">d", meta[i + 3 + len(key):i + 11 + len(key)])[0]
                    if key == b"width": w = int(v)
                    else: h = int(v)
        last = ts; p += 11 + size + 4; n += 1
    return {"format": "flv", "codec": codec, "audio": audio, "width": w or sw, "height": h or sh}


def read_mp4(data):
    if data[4:8] != b"ftyp": raise ValueError("not an MP4")
    codec = "h264" if b"avc1" in data else ("mp4v" if b"mp4v" in data else None)
    w = h = None
    i = data.find(b"tkhd")
    while i >= 0 and not (w and h):      # the first track with a size
        ver = data[i + 4]; off = i + 4 + (88 if ver == 1 else 76)
        ww, hh = struct.unpack(">II", data[off:off + 8])
        if ww and hh: w, h = ww >> 16, hh >> 16
        i = data.find(b"tkhd", i + 4)
    return {"format": "mp4", "codec": codec, "audio": "aac" if b"mp4a" in data else None, "width": w, "height": h, "moov_first": data.find(b"moov") < data.find(b"mdat")}


def read_any(path):
    data = open(path, "rb").read()
    head = data[:8]
    if head[:3] in (b"FWS", b"CWS", b"ZWS"): r = read_swf(data)
    elif head[:3] == b"FLV": r = read_flv(data)
    elif head[4:8] == b"ftyp": r = read_mp4(data)
    elif head[:3] == b"ID3" or (len(data) > 1 and data[0] == 0xff and data[1] & 0xe0 == 0xe0): r = {"format": "mp3"}
    else: r = {"format": "other"}
    r["size"] = len(data); r["sha256"] = hashlib.sha256(data).hexdigest()
    return r


# --- the manifest and the cache ------------------------------------------------------------------------------------------
def load():
    if os.path.exists(MANIFEST): return json.load(open(MANIFEST))
    return {"titles": []}


def save(m):
    m["titles"].sort(key=lambda t: ({"game": 0, "app": 1, "video": 2, "asset": 3}[t["class"]], t.get("kind", ""), t["id"]))
    with open(MANIFEST, "w") as f: json.dump(m, f, indent=1, ensure_ascii=False); f.write("\n")


def cached(t): return os.path.join(CACHE, t["class"], t["id"] + os.path.splitext(urllib.parse.urlparse(t["source"]).path)[1].lower())


def download(url, dest):
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    tmp = dest + ".part"
    with urllib.request.urlopen(req, timeout=180) as r, open(tmp, "wb") as f:
        while True:
            b = r.read(1 << 20)
            if not b: break
            f.write(b)
    os.replace(tmp, dest)


def ia_resolve(src):
    item, _, name = src[3:].partition("/")
    if name: return "https://archive.org/download/%s/%s" % (item, urllib.parse.quote(name)), item
    meta = json.load(urllib.request.urlopen(urllib.request.Request("https://archive.org/metadata/%s/files" % item, headers={"User-Agent": UA}), timeout=60))["result"]
    swfs = [f for f in meta if f["name"].lower().endswith(".swf")]
    if not swfs: raise ValueError("no .swf in %s: %s" % (item, [f["name"] for f in meta][:8]))
    best = max(swfs, key=lambda f: int(f.get("size", 0)))
    return "https://archive.org/download/%s/%s" % (item, urllib.parse.quote(best["name"])), item


def cmd_add(o):
    m = load()
    if any(t["id"] == o.id for t in m["titles"]) and not o.replace: sys.exit("already in the manifest: " + o.id)
    url, item = ia_resolve(o.source) if o.source.startswith("ia:") else (o.source, None)
    t = {"id": o.id, "class": o.cls, "source": url, "input": o.input, "note": o.note}
    if o.kind: t["kind"] = o.kind
    if getattr(o, "for_", None): t["for"] = o.for_
    if o.player: t["player"] = o.player
    if o.media: t["media"] = o.media
    dest = cached(t)
    if not os.path.exists(dest) or o.replace: download(url, dest)
    r = read_any(dest); t.update(r)
    m["titles"] = [x for x in m["titles"] if x["id"] != o.id] + [t]; save(m)
    print(json.dumps({k: t.get(k) for k in ("id", "format", "swf_version", "avm", "width", "height", "fps", "frames", "size", "codec", "embedded_video", "gpu_flag")}))


def cmd_fetch(o):
    m = load(); bad = 0
    for t in m["titles"]:
        if o.ids and t["id"] not in o.ids: continue
        dest = cached(t)
        try:
            if not os.path.exists(dest): download(t["source"], dest); how = "fetched"
            else: how = "cached"
            h = hashlib.sha256(open(dest, "rb").read()).hexdigest()
        except Exception as e:
            print("DEAD %s: %s: %s" % (t["id"], t["source"], e)); bad += 1; continue
        if h != t["sha256"]: print("CHANGED %s: %s has %s, the manifest says %s" % (t["id"], dest, h[:12], t["sha256"][:12])); bad += 1
        elif o.verbose or how == "fetched": print("ok %s %s" % (t["id"], how))
    print("%d titles, %d in trouble; the cache: %s" % (len(m["titles"]), bad, CACHE))
    return 1 if bad else 0


def tracked():
    out = subprocess.run(["git", "-C", ROOT, "ls-files", "-z"], capture_output=True).stdout.decode(errors="replace").split("\0")
    bad = []
    for p in out:
        if not p or p.startswith("third_party/"): continue
        low = p.lower()
        magic = False
        if not low.endswith(MOVIE_EXT):
            full = os.path.join(ROOT, p)
            if low.endswith((".bin", ".dat", ".movie")) and os.path.isfile(full):
                magic = open(full, "rb").read(3) in (b"FWS", b"CWS", b"ZWS", b"FLV")
            if not magic: continue
        if not p.startswith(GENERATED) and not p.startswith("packaging/"): bad.append(p)
    return bad


def cmd_tracked(o=None):
    bad = tracked()
    for p in bad: print("TRACKED, not generated by this project: " + p)
    print("tracked movies: %s" % ("none but the generated" if not bad else "%d to look at" % len(bad)))
    return 1 if bad else 0


def cmd_check(o):
    m = load(); ts = m["titles"]; ok = True
    def say(good, text):
        nonlocal ok
        print(("ok   " if good else "FAIL ") + text); ok = ok and good
    games = [t for t in ts if t["class"] == "game"]; apps = [t for t in ts if t["class"] == "app"]; videos = [t for t in ts if t["class"] == "video"]
    say(len(games) >= 24, "games: %d (at least 24)" % len(games))
    for k in GAME_KINDS:
        n = sum(1 for t in games if t.get("kind") == k); say(n >= 4, "  kind %s: %d (at least 4)" % (k, n))
    for seed in ("helicopter", "bloxorz", "motherload", "qwop", "alien-hominid"): say(any(t["id"] == seed for t in games), "  seed " + seed)
    say(len(apps) >= 8, "apps: %d (at least 8)" % len(apps))
    akinds = {t.get("kind") for t in apps}
    for k in ("draw", "calc", "chart", "music", "form", "viewer"): say(k in akinds, "  app kind " + k)
    say(len(akinds) >= 8, "  app kinds: %d different (%s)" % (len(akinds), ", ".join(sorted(str(x) for x in akinds))))
    say(len(videos) >= 8, "videos: %d (at least 8)" % len(videos))
    def media_of(v):
        return [t for t in ts if t["id"] == (v.get("media") or v["id"])]
    for codec in ("spark", "vp6", "h264"):
        rows = sorted({(media_of(v)[0].get("height") or 0) for v in videos if media_of(v) and media_of(v)[0].get("codec", "") and media_of(v)[0]["codec"].startswith(codec)})
        say(len(rows) >= 2 and max(rows) <= 480, "  codec %s at sizes %s (two or more, up to 480 rows)" % (codec, rows))
    players = {v.get("player") for v in videos if v.get("player")}
    say(len(players) >= 2, "  players: %s (at least 2)" % ", ".join(sorted(players)))
    say(sum(1 for v in videos if v.get("kind") == "cartoon") >= 2, "  authored cartoons: %d (at least 2)" % sum(1 for v in videos if v.get("kind") == "cartoon"))
    movies = [t for t in games + apps + videos if t.get("format") == "swf"]
    vers = sorted({t["swf_version"] for t in movies})
    say(min(vers) <= 6 and all(any(t["swf_version"] == v for t in movies) for v in range(7, 13)), "SWF versions present: %s (6 or older through 12, each)" % vers)
    n1 = sum(1 for t in movies if t["avm"] == 1); n2 = sum(1 for t in movies if t["avm"] == 2)
    say(n1 * 3 >= len(movies) and n2 * 3 >= len(movies), "AVM1 %d, AVM2 %d of %d (each a third or more)" % (n1, n2, len(movies)))
    ws = sorted(t["width"] for t in movies)
    say(ws[0] <= 320 and ws[-1] >= 800, "stage widths %d..%d (320 or less to 800 or more)" % (ws[0], ws[-1]))
    newer = [t["id"] for t in movies if t["swf_version"] > 12]
    say(len(newer) >= 3, "newer than the player (SWF 13+): %s (at least 3)" % ", ".join(newer))
    for t in ts:
        miss = [k for k in ("id", "class", "source", "sha256", "size", "input", "note") if not t.get(k)]
        if t["class"] != "asset" and t.get("format") == "swf": miss += [k for k in ("swf_version", "fps", "width", "height", "avm") if t.get(k) in (None, "")]
        if miss: say(False, "%s lacks %s" % (t["id"], ", ".join(miss)))
    if cmd_tracked(): ok = False
    print("the spread: " + ("met" if ok else "NOT met"))
    return 0 if ok else 1


def cmd_reread(o):
    m = load()
    for t in m["titles"]:
        d = cached(t)
        if os.path.exists(d): t.update(read_any(d))
    save(m)


def cmd_remove(o):
    m = load(); n = len(m["titles"])
    for t in m["titles"]:
        if t["id"] in o.ids and os.path.exists(cached(t)): os.remove(cached(t))
    m["titles"] = [t for t in m["titles"] if t["id"] not in o.ids]; save(m); print("removed %d" % (n - len(m["titles"])))


def cmd_list(o):
    for t in load()["titles"]:
        print("%-5s %-7s %-26s v%-3s avm%-2s %4sx%-4s %5sfps %7dK %s" % (t["class"], t.get("kind", ""), t["id"], t.get("swf_version", "-"), t.get("avm", "-"), t.get("width", "-"), t.get("height", "-"), t.get("fps", "-"), t["size"] // 1024, t.get("codec") or ",".join(t.get("embedded_video", [])) or ""))


def main():
    ap = argparse.ArgumentParser(); sp = ap.add_subparsers(dest="cmd", required=True)
    a = sp.add_parser("read"); a.add_argument("files", nargs="+")
    a = sp.add_parser("add"); a.add_argument("source"); a.add_argument("--id", required=True); a.add_argument("--class", dest="cls", required=True, choices=["game", "app", "video", "asset"])
    a.add_argument("--kind", default=""); a.add_argument("--input", required=True); a.add_argument("--note", required=True); a.add_argument("--for", dest="for_", default=""); a.add_argument("--replace", action="store_true")
    a.add_argument("--player", default="", help="a video: the id of the player movie (an asset) that plays it"); a.add_argument("--media", default="", help="a video: the id of its media file, itself when empty")
    a = sp.add_parser("fetch"); a.add_argument("ids", nargs="*"); a.add_argument("-v", dest="verbose", action="store_true")
    sp.add_parser("check"); sp.add_parser("tracked"); sp.add_parser("list"); sp.add_parser("reread")
    a = sp.add_parser("remove"); a.add_argument("ids", nargs="+")
    a = sp.add_parser("path"); a.add_argument("id")
    o = ap.parse_args()
    if o.cmd == "read":
        for f in o.files: print(f, json.dumps(read_any(f)))
    elif o.cmd == "add": cmd_add(o)
    elif o.cmd == "fetch": sys.exit(cmd_fetch(o))
    elif o.cmd == "check": sys.exit(cmd_check(o))
    elif o.cmd == "tracked": sys.exit(cmd_tracked(o))
    elif o.cmd == "list": cmd_list(o)
    elif o.cmd == "reread": cmd_reread(o)
    elif o.cmd == "remove": cmd_remove(o)
    elif o.cmd == "path":
        for t in load()["titles"]:
            if t["id"] == o.id: print(cached(t))


if __name__ == "__main__":
    main()
